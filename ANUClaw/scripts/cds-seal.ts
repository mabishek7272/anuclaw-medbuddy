/**
 * Seal the CDS data files: recompute each file's canonical SHA-256 and write
 * the integrity manifest. Run this after ANY change to a sealed data file:
 *
 *   tsx scripts/cds-seal.ts
 *
 * This is the change-control step that makes a data edit deliberate: an
 * unsealed edit is detected by the registry and halts the pipeline
 * (plan §3.3, §4.1.3, §4.2.3). Sealing should be gated by Change Control Board
 * review (plan §11.2) in a real deployment.
 */

import * as fs from 'fs';
import * as path from 'path';
import { contentHash } from '../src/cds/hashing';
import { cyp2d6 } from '../src/cds/data/cyp2d6';
import { cyp2c19 } from '../src/cds/data/cyp2c19';
import { cpicRules } from '../src/cds/data/cpic-rules';
import { contraindications } from '../src/cds/safety/data/contraindications';
import { drugInteractions } from '../src/cds/safety/data/drug-interactions';
import { allergyRules } from '../src/cds/safety/data/allergy-rules';
import { citations } from '../src/cds/evidence/data/citations';

const sealed: Array<{ data_id: string }> = [
  cyp2d6,
  cyp2c19,
  cpicRules,
  contraindications,
  drugInteractions,
  allergyRules,
  citations,
];

const manifest: Record<string, string> = {};
for (const data of sealed) {
  manifest[data.data_id] = contentHash(data);
}

const body = Object.entries(manifest)
  .map(([id, hash]) => `  '${id}': '${hash}',`)
  .join('\n');

const out = `// AUTO-GENERATED by scripts/cds-seal.ts — do not edit by hand.
// Regenerate after any change to a sealed CDS data file:  tsx scripts/cds-seal.ts
//
// Maps each data file's \`data_id\` to the SHA-256 of its canonical content.
// The registry verifies every data file against this manifest on load and
// fails closed on any mismatch (plan §3.3 "Rule table version mismatch -> Halt").
export const integrityManifest: Record<string, string> = {
${body}
};
`;

const manifestPath = path.resolve(__dirname, '../src/cds/data/manifest.ts');
fs.writeFileSync(manifestPath, out, 'utf8');

console.log('Sealed CDS data files:');
for (const [id, hash] of Object.entries(manifest)) {
  console.log(`  ${id.padEnd(12)} ${hash}`);
}
console.log(`\nManifest written to ${manifestPath}`);
